// Node 22與系統Edge，離線生成游標資產，不開啟可見視窗或操作系統游標。
import {spawn} from 'node:child_process';
import {mkdtemp,readFile,writeFile,mkdir,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join,resolve,relative,isAbsolute} from 'node:path';
import {fileURLToPath} from 'node:url';
import {setTimeout as delay} from 'node:timers/promises';

const root=resolve(fileURLToPath(new URL('../',import.meta.url))),output=join(root,'assets/cursors');
const profile=await mkdtemp(join(tmpdir(),'winding-cursor-build-'));
const edge=spawn(process.env.WINDING_EDGE||'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',['--headless=new','--no-first-run','--no-default-browser-check','--remote-debugging-port=0',`--user-data-dir=${profile}`,'about:blank'],{windowsHide:true,stdio:'ignore'});
let socket,id=0;const pending=new Map();
async function until(check){for(let n=0;n<150;n++){try{const value=await check();if(value)return value;}catch(_){}await delay(100);}throw new Error('Cursor build browser timed out');}
function send(method,params={}){return new Promise((resolve,reject)=>{const next=++id,timer=setTimeout(()=>{pending.delete(next);reject(new Error(`CDP timeout: ${method}`));},15000);pending.set(next,{resolve,reject,timer});socket.send(JSON.stringify({id:next,method,params}));});}
async function evaluate(expression){const r=await send('Runtime.evaluate',{expression,awaitPromise:true,returnByValue:true});if(r.exceptionDetails)throw new Error(r.exceptionDetails.exception?.description||r.exceptionDetails.text);return r.result.value;}
try{
    const port=await until(async()=>Number((await readFile(join(profile,'DevToolsActivePort'),'utf8')).split('\n')[0]));
    const targets=await (await fetch(`http://127.0.0.1:${port}/json/list`)).json();
    socket=new WebSocket(targets.find(t=>t.type==='page').webSocketDebuggerUrl);
    await new Promise((resolve,reject)=>{socket.onopen=resolve;socket.onerror=reject;});
    socket.onmessage=e=>{const m=JSON.parse(e.data),task=pending.get(m.id);if(task){pending.delete(m.id);clearTimeout(task.timer);if(m.error)task.reject(new Error(m.error.message));else task.resolve(m.result);}};
    await send('Runtime.enable');
    await evaluate(await readFile(join(root,'tools/crystal-cursor-source.js'),'utf8'));
    const frames=await evaluate('createCrystalCursorFrames().map(c=>c.toDataURL("image/png"))');
    const black=await evaluate('(()=>{const c=document.createElement("canvas");c.width=c.height=32;const ctx=c.getContext("2d");ctx.fillStyle="#000";ctx.fillRect(0,0,1,1);return c.toDataURL("image/png");})()');
    await mkdir(output,{recursive:true});
    await writeFile(join(output,'crystal-frames.js'),`'use strict';\n// Generated by tools/build-cursors.mjs.\nwindow.windingCursorFrames=${JSON.stringify({width:32,height:32,hotspot:[3,2],duration:6000,frames})};\n`);
    await writeFile(join(output,'crystal-arrow.png'),Buffer.from(frames[0].split(',')[1],'base64'));
    await writeFile(join(output,'black-dot.png'),Buffer.from(black.split(',')[1],'base64'));
    console.log(`Generated ${frames.length} cursor frames, crystal-arrow.png and black-dot.png.`);
}finally{
    if(socket?.readyState===WebSocket.OPEN){try{await send('Browser.close');}catch(_){}socket.close();}
    for(const task of pending.values())clearTimeout(task.timer);
    edge.kill();await delay(250);
    const location=relative(resolve(tmpdir()),resolve(profile));
    if(location.startsWith('..')||isAbsolute(location))throw new Error('Unexpected temporary profile path');
    await rm(profile,{recursive:true,force:true,maxRetries:6,retryDelay:200});
}
